/**
 * Shows the initial setup screen (500x400, non-resizable).
 * On save, updates config.firstBoot=false + language + advancedMode.
 * @param {Function} onDone - callback when setup is completed
 */
function showSetupWindow(onDone) {
  if (setupWindow && !setupWindow.isDestroyed()) {
    setupWindow.focus();
    return;
  }

  const { BrowserWindow } = require('electron');
  const path = require('path');

  setupWindow = new BrowserWindow({
    width: 500,
    height: 400,
    minWidth: 500,
    minHeight: 400,
    maxWidth: 500,
    maxHeight: 400,
    resizable: false,
    maximizable: false,
    fullscreenable: false,
    useContentSize: true, // exact HTML geometry vs OS title bars
    backgroundColor: '#0a0a0f',
    icon: path.join(__dirname, '..', 'assets', 'icon.png'),
    title: 'Shinobi Launcher — Setup',
    show: false,
    autoHideMenuBar: true,
    webPreferences: {
      nodeIntegration: false,
      contextIsolation: true,
      backgroundThrottling: false
    }
  });

  // Passes current language via query string (setup.html now in ui/setup/)
  const setupUrl =
    'file://' +
    path.join(__dirname, 'ui', 'setup', 'setup.html') +
    '?lang=' +
    (config.language || 'pt');
  setupWindow.loadURL(setupUrl);

  setupWindow.once('ready-to-show', function () {
    setupWindow.show();
    logger.info('Setup window shown (firstBoot)');
  });

  // Intercepts "close" — setup.html signals via document.title '__SETUP_DONE__{json}'
  setupWindow.on('page-title-updated', function (e, title) {
    if (typeof title === 'string' && title.indexOf('__SETUP_DONE__') === 0) {
      e.preventDefault();
      try {
        const jsonStr = title.slice('__SETUP_DONE__'.length);
        const result = JSON.parse(jsonStr);
        logger.info(
          'Setup complete: lang=' +
            result.language +
            ' region=' +
            (result.region || 'br') +
            ' advanced=' +
            result.advancedMode
        );

        // Apply settings
        config.firstBoot = false;
        config.language = result.language || 'pt';
        config.region = result.region || 'br'; // region selector no setup
        config.advancedMode = result.advancedMode === true;

        // Sync i18n
        i18n.setLanguage(config.language);

        // Persists
        _persistConfig();

        // Recreate mms.cfg with Advanced Light Mode if enabled
        try {
          const { createMmsCfg } = require('./flash/mms');
          createMmsCfg(config.hardwareProfile, { advancedMode: config.advancedMode });
        } catch (_) {
          /* ignore */
        }

        // Closes setup and calls callback
        setupWindow.destroy();
        setupWindow = null;
        if (onDone) onDone();
      } catch (err) {
        logger.error('Failed to process setup result: ' + err.message);
      }
    }
  });

  // If user closes without saving (X), cancel and reopen next time
  setupWindow.on('closed', function () {
    setupWindow = null;
    // If firstBoot is still true (didn't save), keep for next time
    if (config.firstBoot !== false) {
      logger.warn('Setup closed without completing — firstBoot preserved for next launch');
      // Don't call onDone → app doesn't continue, closes
      app.quit();
    }
  });
}

app.on('ready', function () {
  // Flash PPAPI is bundled in the repo (flash/libpepflashplayer.so | pepflashplayer.dll).
  // If not accessible, the installation is corrupted — there is no download fallback.
  if (!flashPath) {
    _showFlashMissingError();
    return;
  }

  // Subsystems
  profileStore.load();

  // EventTimers with full profiles (respects notificationsEnabled per profile)
  eventTimers.startWithProfiles(profileStore.getAll());

  // NO TRAY — app exits when all windows close.

  // ── ONBOARDING — if firstBoot, show setup before manager ──
  if (config.firstBoot !== false) {
    logger.info('First run detected — opening setup window');
    showSetupWindow(function onSetupDone() {
      _initManagerAndLaunch();
    });
    return;
  }

  _initManagerAndLaunch();
});

/**
 * Flash PPAPI missing = corrupted installation.
 * The binary is committed in the repo (flash/); no on-demand download.
 * Shows a dialog and exits — user must reinstall the launcher.
 */
function _showFlashMissingError() {
  logger.error('Flash PPAPI not found — corrupted installation');
  dialog.showMessageBoxSync({
    type: 'error',
    title: 'Flash not found',
    message: 'The Flash PPAPI plugin was not found.',
    detail:
      'The Shinobi Launcher installation appears corrupted — the Flash binary ' +
      'comes bundled in the repository with no automatic download.\n\n' +
      'Reinstall the launcher by downloading the latest version from GitHub.\n' +
      'Flash is required to run Naruto Online.',
    buttons: ['Exit']
  });
  app.exit(1);
}

/**
 * Initializes UI Manager + banner (separate to call after setup).
 */
function _initManagerAndLaunch() {
  // Recreate mms.cfg with Advanced Light Mode if enabled in config
  try {
    const { createMmsCfg } = require('./flash/mms');
    createMmsCfg(config.hardwareProfile, { advancedMode: config.advancedMode === true });
  } catch (_) {
    /* ignore */
  }

  // UI Manager — skip in Minimal Mode (manager-only saves 45MB on PCs <2GB)
  uiManager = require('./ui/controller');
  uiManager.registerIpcHandlers({
    launchProfile: launchGameForProfile,
    closeProfile: profileManager.close, // close game window by profile ID
    getEvents: function (region) {
      return eventTimers.getUpcoming(region || 'br');
    },
    setMuted: function (m) {
      eventTimers.setMuted(m);
      _persistConfig();
    },
    getVault: function (profileId) {
      return vault.getCredentials(profileId);
    },
    setVault: function (profileId, user, pass) {
      return vault.setCredentials(profileId, user, pass);
    },
    removeVault: function (profileId) {
      return vault.removeCredentials(profileId);
    },
    hasVault: function (profileId) {
      return vault.hasCredentials(profileId);
    },
    isLowSpecMode: function () {
      return memoryGuard.isLowSpecMode();
    },
    isMinimal: function () {
      return memoryGuard.isMinimal();
    },
    toggleLowSpec: function () {
      memoryGuard.setForceLowSpec(!memoryGuard.isLowSpecMode());
      partition.setLowSpecMode(memoryGuard.isLowSpecMode());
      _persistConfig();
      return memoryGuard.isLowSpecMode();
    }
  });

  // ── Optimization IPC handlers (GPU + CPU + presets) ──
  // gpuDetector is already required at top-level (for getEnvVars before ready)
  const cpuOptimizer = require('./app/CpuOptimizer');
  const { listForUI, getDefaultPreset } = require('./config/optimization');

  ipcMain.handle('optimization:get-status', function () {
    const gpu = gpuDetector.detect();
    const cpu = cpuOptimizer.getStats();
    const snap = flags.getAppliedSnapshot();
    return {
      preset: config.optimizationPreset || getDefaultPreset(),
      presets: listForUI(),
      // expose advancedMode (Modo PC Fraco) so the UI toggle reflects persisted state.
      advancedMode: config.advancedMode === true,
      // expose cpuRender (Force CPU rendering) — maps to hardwareProfile='cpu'.
      cpuRender: config.hardwareProfile === 'cpu',
      gpu: {
        vendor: gpu.vendor,
        description: gpu.description,
        isPrime: gpu.isPrime,
        hasNvidia: gpu.hasNvidia,
        hasAmd: gpu.hasAmd,
        hasIntel: gpu.hasIntel,
        allGpus: gpu.allGpus.map(function (g) {
          return { vendor: g.vendor, description: g.description };
        })
      },
      cpu: {
        totalCores: cpu.topology.totalCores,
        pCores: cpu.topology.pCores.length,
        eCores: cpu.topology.eCores.length,
        isHybrid: cpu.topology.isHybrid,
        appliedPids: cpu.appliedPids,
        platform: cpu.platform
      },
      applied: snap,
      systemRamGb: flags.SYSTEM_RAM_GB,
      isLowSpec: flags.IS_LOW_SPEC,
      isWayland: flags.IS_WAYLAND
    };
  });

  // PRESETS/listForUI are kept for backwards compat with optimization:get-status response.

  // Toggle Modo PC Fraco (advancedMode / Flash low quality).
  // Re-creates mms.cfg immediately so the change takes effect on next game launch
  // (no launcher restart needed — only the Flash plugin reads mms.cfg at load).
  ipcMain.handle('optimization:set-lowpc', function (_e, enabled) {
    const newState = enabled === true;
    const previous = config.advancedMode === true;
    if (previous === newState) {
      return { ok: true, previous: previous, current: newState, changed: false };
    }
    config.advancedMode = newState;
    _persistConfig();
    try {
      const { createMmsCfg } = require('./flash/mms');
      createMmsCfg(config.hardwareProfile, { advancedMode: newState });
    } catch (err) {
      logger.error('Failed to recreate mms.cfg (lowpc toggle): ' + err.message);
    }
    logger.info('Low-end PC mode (advancedMode): ' + (newState ? 'ON' : 'OFF'));
    return {
      ok: true,
      previous: previous,
      current: newState,
      changed: true
    };
  });

  // Toggle Force CPU rendering (hardwareProfile='cpu' / disable-gpu).
  // Persisted to config; flags.js reads hardwareProfile at boot to decide whether
  // to append --disable-gpu + --use-gl=swiftshader. Requires launcher restart —
  // Chromium flags can't be changed at runtime.
  // When OFF, hardwareProfile='modern' (the default — GPU rendering enabled).
  ipcMain.handle('optimization:set-cpu-render', function (_e, enabled) {
    const newState = enabled === true;
    const previous = config.hardwareProfile === 'cpu';
    if (previous === newState) {
      return { ok: true, previous: previous, current: newState, changed: false };
    }
    config.hardwareProfile = newState ? 'cpu' : 'modern';
    _persistConfig();
    logger.info('Force CPU rendering (hardwareProfile): ' + (newState ? 'cpu' : 'modern'));
    return {
      ok: true,
      previous: previous,
      current: newState,
      changed: true
    };
  });

  // Register preload API handlers (game windows use narutoLauncher API)
  const pkg = require('../package.json');
  ipcMain.handle('launcher:get-version', function () {
    return pkg.version || 'unknown';
  });

  uiManager.createManagerWindow(); // always creates (no tray for fallback)

  _logBanner();
  // flashPath is guaranteed non-null here — boot would
  // branch to _provisionFlashAndRelaunch() otherwise. The UI still
  // may show a warning if the version is unexpected, but doesn't block.
}

app.on('before-quit', function () {
  isQuitting = true;
});

// NO TRAY — when all windows close, the app exits.
// (Previously stayed in tray without restore → "try to close and it doesn't")
app.on('window-all-closed', function () {
  app.quit();
});

// ── Child process crash monitoring ──
// These events do NOT close the main app — we only log for diagnostics.
// Each game BrowserWindow already handles 'render-process-gone' independently
// (in game-launcher.js), but GPU/child-process events are global.
app.on('gpu-process-crashed', function (event) {
  const reason = (event && event.reason) || 'unknown';
  const exitCode = (event && event.exitCode) || '?';
  logger.error('⚡ GPU process crashed — reason=' + reason + ' exitCode=' + exitCode);
});

app.on('child-process-gone', function (event, details) {
  logger.warn(
    '⚡ Child process gone — type=' +
      details.type +
      ' reason=' +
      details.reason +
      ' exitCode=' +
      details.exitCode
  );
});

app.on('will-quit', function () {
  try {
    const { restoreMmsCfg } = require('./flash/mms');
    restoreMmsCfg();
  } catch (_) {
    /* ignore */
  }
  eventTimers.stop();
});

// Graceful exit
process.on('SIGTERM', function () {
  isQuitting = true;
  app.quit();
});
process.on('SIGINT', function () {
  isQuitting = true;
  app.quit();
});
process.on('uncaughtException', function (e) {
  logger.error('Uncaught: ' + e.message + '\n' + (e.stack || ''));
  isQuitting = true;
  app.quit();
});
process.on('unhandledRejection', function (reason) {
  logger.error('Unhandled rejection: ' + reason);
});

// ═══════════════════════════════════════════════════════════════════════════
// HELPERS
