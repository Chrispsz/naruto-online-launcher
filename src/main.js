/**
 * Shinobi Launcher — main.js (thin bootstrap)
 *
 * MAIN ORCHESTRATOR
 *
 *   Multi-region (BR/NA/EU/HK/DE/ES/PL/FR) with per-profile language (pt/en/de/es/pl/fr).
 *   Encrypted backup AES-256-GCM + PBKDF2 with master password.
 *   No tracking — local logs on disk.
 *   Diagnostics exporter in Settings → Advanced (explicit opt-in).
 *
 * BOOT ORDER (CRITICAL):
 *   1. [top-level, before ready] loadConfig (sync) + findFlashPlugin
 *   2. [top-level, before ready] main/flags.applyAll() ← ONLY place that touches commandLine
 *   3. [ready] subsystems: store.load, guard.start, eventTimers.startWithProfiles
 *   4. [ready] ui/controller.createManagerWindow()
 *
 * ARCHITECTURE:
 *   Electron 11.5.0 (LAST with PPAPI Flash) + Clean Flash 34.0 bundled.
 *   UI in vanilla JS/HTML/CSS (zero framework inside Electron) = ~45MB RAM idle.
 *   Tauri does NOT run Flash (WebView2/WebKitGTK removed PPAPI since Chrome 88).
 */

'use strict';

// ── MESA env migration (before anything else) ──
// MESA_GLSL_CACHE_DISABLE was renamed to MESA_SHADER_CACHE_DISABLE in
// recent Mesa versions and emits a deprecation warning every boot.
// We silently migrate preserving the user's intent (if they set
// the old name in the shell). vblank_mode is intentional (user vsync) —
// we don't touch it.
(function _migrateMesaEnv() {
  if (
    process.env.MESA_GLSL_CACHE_DISABLE !== undefined &&
    process.env.MESA_SHADER_CACHE_DISABLE === undefined
  ) {
    process.env.MESA_SHADER_CACHE_DISABLE = process.env.MESA_GLSL_CACHE_DISABLE;
  }
  delete process.env.MESA_GLSL_CACHE_DISABLE;
})();

// NOTE — Fontconfig warnings ("invalid attribute 'xsi:nil'" /
// "invalid constant used"): are host system noise, not from the launcher.
// Come from /etc/fonts/conf.d/48-guessfamily.conf (invalid XML generated by a
// schema-aware tool on some distros). The AppImage can't
// fix /etc/fonts — these warnings are harmless (fonts continue
// working) and don't affect the game. To silence permanently, the
// user can remove/repair that system file.

const { app, dialog, ipcMain } = require('electron');
const path = require('path');

// ═══════════════════════════════════════════════════════════════════════════
// BOOT PHASE 1 — BEFORE app.ready (flags MUST be applied here)
// ═══════════════════════════════════════════════════════════════════════════

const logger = require('./utils/logger');

const { loadConfig } = require('./config/settings');
const { findFlashPlugin, getFlashVersion } = require('./flash/plugin');
const flags = require('./main/flags');

// Config sync (app.getPath('userData') is valid before ready)
let config = loadConfig();

// Flash detection (path + version only — flags.js handles the rest)
const flashPath = findFlashPlugin();
const flashVersion = flashPath ? getFlashVersion(path.dirname(flashPath)) : null;

// ══ APPLY GPU ENV VARS BEFORE READY ══
// GpuDetector.getEnvVars() returns GPU-specific env vars
// (NVIDIA __GL_*, AMD RADEONSI_ZERO_VRAM, Intel INTEL_DEBUG, MALLOC_ARENA_MAX, etc.)
// GPU env vars must be set BEFORE app.whenReady() so the GPU process inherits them.
const gpuDetector = require('./app/GpuDetector');
const gpuEnvVars = gpuDetector.getEnvVars(config.optimizationPreset || 'balanced');
for (var _envKey in gpuEnvVars) {
  if (Object.prototype.hasOwnProperty.call(gpuEnvVars, _envKey)) {
    process.env[_envKey] = gpuEnvVars[_envKey];
  }
}
if (Object.keys(gpuEnvVars).length > 0) {
  logger.info('GPU env vars applied: ' + Object.keys(gpuEnvVars).join(', '));
}

// ══ APPLY ALL FLAGS BEFORE READY ══
// (main/flags.js is the ONLY authority over commandLine.appendSwitch)
flags.applyAll({
  flashPath: flashPath,
  flashVersion: flashVersion,
  hardwareProfile: config.hardwareProfile,
  forceLowSpec: config.forceLowSpec === true,
  optimizationPreset: config.optimizationPreset
});

// Single Instance Lock
const gotTheLock = app.requestSingleInstanceLock();
if (!gotTheLock) {
  app.quit();
}

