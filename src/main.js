// GAME LAUNCH — no tray (user request: "don't want it in the tray")
// ═══════════════════════════════════════════════════════════════════════════

/**
 * Launches the game for a profile DELEGATING to ProfileManager (facade).
 *
 * MULTI-ACCOUNT: the manager STAYS VISIBLE when a game opens, so
 * the user can Play other accounts simultaneously (each profile
 * already runs in an isolated partition/window — no process conflicts). Previously the
 * manager was hidden to free ~45MB of RAM; today this is irrelevant on
 * machines with ≥4GB and prevented multi-account use. In Minimal Mode (<2GB RAM)
 * the old behavior (hide) is kept due to memory constraints.
 *
 * Flow: Play → game window opens (isolated) → manager stays visible →
 * user can open N accounts. Closing the manager (X) with games running only
 * hides it; it returns when the last game closes.
 */
function launchGameForProfile(profileId) {
  if (!uiManager) {
    uiManager = require('./ui/controller');
    if (!uiManager.getManagerWindow()) uiManager.createManagerWindow();
  }
  profileManager.launch(
    profileId,
    function onOpened() {
      activeGameWindows++;
      // Minimal Mode (PC <2GB): hides the manager to free RAM (legacy behavior).
      // Otherwise: manager stays visible → simultaneous multi-account enabled.
      if (memoryGuard.isMinimal() && uiManager) {
        uiManager.hideManager();
        logger.info('Manager hidden (Minimal Mode) — RAM freed for game');
      } else {
        logger.info('Game opened — manager visible (multi-account available)');
      }
    },
    function onClosed() {
      activeGameWindows = Math.max(0, activeGameWindows - 1);
      if (activeGameWindows === 0 && uiManager) {
        // Last game closed: ensures the manager is visible (in case the
        // user hid it manually via X during the game).
        uiManager.showManager();
        logger.info('Game closed — manager restored');
      }
    }
  );
}

function showManager() {
  if (!uiManager) {
    uiManager = require('./ui/controller');
    if (!uiManager.getManagerWindow()) uiManager.createManagerWindow();
    return;
  }
  uiManager.showManager();
}

